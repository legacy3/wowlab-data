def _config_ok(compiler: Compiler, class_id: int, spec_id: int, level: int, ranks: dict[int, int], hero: int | None) -> bool:
    cfg = compiler.trait_config(spec_id, class_id, level, sorted(ranks.items()), hero, simulate_load_path=False)
    return not cfg["errors"] and not cfg["strict"] and all(r["ok"] for r in cfg["currencies"])


def starter_traits(compiler: Compiler, class_id: int, spec_id: int, level: int = FIXTURE_LEVEL
                   ) -> tuple[list[dict[str, int]], int | None, int, list[str]]:
    """(entries, hero_subtree_id, loadout_id, notes): the authored starter build replayed step by step.

    ``TraitTreeLoadoutEntry.NumPoints`` is the cumulative rank at each ``OrderIndex`` step and the authored builds
    spend the level-90 budget, so each step is kept only while the whole config stays valid for ``level``
    (TraitMgr::ValidateConfig port + owned currency).  Saved ranks exclude granted ranks (Player.cpp:28533-28550).
    The hero sub-tree is the lowest-id sub-tree the spec may select; its nodes are added greedily (lowest node id,
    first entry, full rank) while the config stays valid.  Synthetic choices, labelled in the notes.
    """
    snap = compiler.snap
    t = snap.traits
    trees, _ = snap.class_trait_trees(class_id)
    loadouts = [(lid, tree) for lid, tree in t["loadouts"].get(spec_id, []) if tree in trees]
    if not loadouts:
        raise SourceError(f"spec {spec_id} has no TraitTreeLoadout on its class trees {trees}")
    lid, tree = max(loadouts)
    notes: list[str] = []
    others = sorted({tr for _, tr in t["loadouts"].get(spec_id, []) if tr not in trees})
    if others:
        notes.append(f"spec {spec_id} also has TraitTreeLoadout rows on trees {others}, which Trinity never loads for class "
                     f"{class_id} (class trees {trees}); ignored")
    engine = TraitEngine(t, spec_id, class_id, level, trees)
    granted = {g["entry"]: g["granted"] for g in engine.granted_entries()}
    ranks: dict[int, int] = {}
    kept = skipped = 0
    for row in sorted(t["loadout_entries"].get(lid, []), key=lambda r: r["order"]):
        entry_id = row["entry"]
        if not entry_id:
            cands = t["node_entries"].get(row["node"], [])
            if len(cands) != 1:
                skipped += 1
                continue
            entry_id = cands[0]
        target = row["points"] - granted.get(entry_id, 0)
        if target <= ranks.get(entry_id, 0):
            continue
        trial = dict(ranks)
        trial[entry_id] = target
        if _config_ok(compiler, class_id, spec_id, level, trial, None):
            ranks = trial
            kept += 1
        else:
            skipped += 1
    notes.append(f"starter build TraitTreeLoadout {lid} (tree {tree}) replayed in OrderIndex order at level {level}: "
                 f"{kept} steps kept, {skipped} steps skipped (invalid or over budget at this level; the authored build "
                 f"spends the level-90 budget)")

    hero = None
    for st_id, st in sorted(t["subtree"].items()):
        if st["tree"] in trees and _config_ok(compiler, class_id, spec_id, level, ranks, st_id):
            hero = st_id
            break
    if hero is None:
        notes.append("no selectable hero sub-tree at this level")
    else:
        added = 0
        hero_nodes = sorted(n for n in t["tree_nodes"].get(t["subtree"][hero]["tree"], []) if t["node"][n]["subtree"] == hero)
        changed = True
        while changed:
            changed = False
            for node_id in hero_nodes:
                node_entries = t["node_entries"].get(node_id, [])
                if any(e in ranks for e in node_entries):
                    continue
                for e in node_entries:
                    target = t["entry"][e]["max_ranks"] - granted.get(e, 0)
                    if target <= 0:
                        continue
                    trial = dict(ranks)
                    trial[e] = target
                    if _config_ok(compiler, class_id, spec_id, level, trial, hero):
                        ranks = trial
                        added += 1
                        changed = True
                        break
        notes.append(f"hero sub-tree {hero} ({t['subtree'][hero]['name']}): lowest selectable sub-tree id; {added} nodes "
                     f"added greedily (lowest node id, first valid entry, full rank); granted entry nodes excluded")
    out = [{"node_entry_id": e, "rank": r} for e, r in sorted(ranks.items())]
    return out, hero, lid, notes


