#: no-fill-rule variants: the same source identities without the base-stat fill-rule opt-in.  player_classlevelstats has
#: no level-90 row, so /derived/stats must be unresolved (never interpolated); agent F's differential opts into the fill
#: rule for it by itself (witness of the level-81..90 base-stat gap).
NO_FILL_RULE_VARIANTS = {"arms-warrior-plate-2h": "arms-warrior-plate-2h-no-fill-rule"}


def build_fixtures(compiler: Compiler) -> dict[str, dict[str, Any]]:
    pools = _corpus_pools(compiler.snap)
    out = {plan["name"]: build_fixture(compiler, plan, pools) for plan in FIXTURE_PLAN}
    for base, name in NO_FILL_RULE_VARIANTS.items():
        fx = json.loads(json.dumps(out[base]))
        fx["server_inputs"]["base_stats"].pop("fill_rule", None)
        fx["provenance"]["notes"].append(
            f"NO-FILL-RULE VARIANT of {base}: identical source identities without the base-stat fill-rule opt-in; "
            f"player_classlevelstats has no level-{FIXTURE_LEVEL} row, so /derived/stats must be unresolved (never interpolated)")
        out[name] = fx
    return out


def write_fixtures(compiler: Compiler, out_dir: Path = FIXTURES_DIR) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    fixtures = build_fixtures(compiler)
    # the directory is generated: stale fixtures (renamed plans) would otherwise be compiled into the index
    for stale in sorted(out_dir.glob("*.json")):
        stem = stale.name.removesuffix(".compiled.json").removesuffix(".json")
        if stale.name != "index.json" and stem not in fixtures:
            stale.unlink()
    paths = []
    for name, fixture in fixtures.items():
        Fixture.from_dict(fixture)             # structural validation before writing
        path = out_dir / f"{name}.json"
        path.write_text(canonical_json(fixture), encoding="utf-8")
        paths.append(path)
    return paths


