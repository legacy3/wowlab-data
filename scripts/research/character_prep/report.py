def _corpus_pools(snapshot: Snapshot) -> dict[str, Any]:
    if not GEAR_CORPUS.exists():
        raise SourceError(f"missing {GEAR_CORPUS}")
    corpus = json.loads(GEAR_CORPUS.read_text(encoding="utf-8"))
    pools: dict[tuple[str, int, int], list[int]] = defaultdict(list)   # (kind, class, subclass) -> ids
    by_inv: dict[tuple[str, int], list[int]] = defaultdict(list)
    seen: set[int] = set()
    expansion = {r[0]: r[1] for r in snapshot.source.project("ItemSparse", ("ID", "ExpansionID"))}
    for kind in ("raid", "mythic_plus"):
        for item in corpus[kind]["items"]:
            iid = int(item["item_id"])
            if iid in seen or not item["variants"] or expansion.get(iid) != CURRENT_EXPANSION_ID:
                continue
            seen.add(iid)
            proto = snapshot.gear.items.get(iid)
            pools[(kind, proto.class_id, proto.subclass_id)].append(iid)
            by_inv[(kind, proto.inventory_type)].append(iid)
    return {"pools": {k: sorted(v) for k, v in pools.items()}, "by_inv": {k: sorted(v) for k, v in by_inv.items()},
            "ids": seen, "window": corpus["window"]}


def _pick(snapshot: Snapshot, pools: dict[str, Any], kind: str, armor_subclass: int, inv_types: tuple[int, ...],
          exclude: set[int]) -> int | None:
    for iid in pools["pools"].get((kind, 4, armor_subclass), []):
        proto = snapshot.gear.items.get(iid)
        if proto.inventory_type in inv_types and iid not in exclude:
            return iid
    return None


def _pick_inv(pools: dict[str, Any], kind: str, inv: int, exclude: set[int]) -> int | None:
    for iid in pools["by_inv"].get((kind, inv), []):
        if iid not in exclude:
            return iid
    return None


def _entry(snapshot: Snapshot, pools: dict[str, Any], item_id: int, *, extra_bonus: list[int] = (), gems: list[int] = (),
           enchants: list[int] = (), tier: bool = False) -> dict[str, Any]:
    proto = snapshot.gear.items.get(item_id)
    entry: dict[str, Any] = {"item_id": item_id}
    in_raid = item_id in pools["by_inv"].get(("raid", proto.inventory_type), [])
    if tier:
        entry["context"] = TIER_CONTEXT
        entry["label"] = "tier piece (ItemSet/ItemSparse; not in current-gear corpus)"
    elif in_raid:
        entry["context"] = RAID_CONTEXT
    else:
        entry["context"] = MP_CONTEXT
        entry["mythic_plus_keystone_level"] = MP_KEY
    if extra_bonus:
        entry["bonus_list_ids"] = list(extra_bonus)
    if gems:
        entry["gems"] = list(gems)
    if enchants:
        entry["enchant_ids"] = list(enchants)
    return entry


