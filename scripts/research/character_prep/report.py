def cmd_synth_fixtures(args: Any) -> int:
    compiler = Compiler(Snapshot(args.tables) if args.tables else Snapshot())
    for path in write_fixtures(compiler, Path(args.out_dir) if args.out_dir else FIXTURES_DIR):
        print(f"wrote {path}")
    return 0


def cmd_all(args: Any) -> int:
    from . import graph as graph_mod
    from . import inputs as inputs_mod
    from .fixture import schema_document
    CORPORA.mkdir(parents=True, exist_ok=True)
    compiler = Compiler(Snapshot(args.tables) if args.tables else Snapshot())
    written = [CORPORA / "fixture-schema.json"]
    written[0].write_text(canonical_json(schema_document()), encoding="utf-8")
    written += inputs_mod.write_corpora(compiler.snap)
    written.append(graph_mod.write_corpus())
    write_fixtures(compiler)
    index = compile_all(compiler)
    for path in written:
        print(f"wrote {path}")
