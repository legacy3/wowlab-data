def build_fixture(compiler: Compiler, plan: dict[str, Any], pools: dict[str, Any]) -> dict[str, Any]:
    snapshot = compiler.snap
    entries, hero, loadout_id, notes = starter_traits(compiler, plan["class"], plan["spec"], FIXTURE_LEVEL)
    armor = ARMOR[plan["armor"]]
    prefer = plan.get("prefer", "raid")
    other = "mythic_plus" if prefer == "raid" else "raid"
    used: set[int] = set(plan["weapons"].values()) | set(plan.get("tier", []))
    equipment: dict[str, dict[str, Any]] = {}
    tier_slots: dict[str, int] = {}
    for iid in plan.get("tier", []):
        proto = snapshot.gear.items.get(iid)
        for slot, invs in ARMOR_SLOT_INVTYPE.items():
            if proto.inventory_type in invs and slot not in tier_slots:
                tier_slots[slot] = iid
                break
    for slot, invs in ARMOR_SLOT_INVTYPE.items():
        if slot in tier_slots:
            equipment[slot] = _entry(snapshot, pools, tier_slots[slot], tier=True,
                                     enchants=plan.get("enchants", {}).get(slot, ()))
            continue
        iid = _pick(snapshot, pools, prefer, armor, invs, used) or _pick(snapshot, pools, other, armor, invs, used)
        if iid is None and slot == "BACK":
            iid = _pick(snapshot, pools, prefer, 1, invs, used) or _pick(snapshot, pools, other, 1, invs, used)
        if iid is None:
            raise SourceError(f"{plan['name']}: no {plan['armor']} item for {slot} in the current-gear corpus")
        used.add(iid)
        equipment[slot] = _entry(snapshot, pools, iid, enchants=plan.get("enchants", {}).get(slot, ()))
    neck = _pick_inv(pools, prefer, 2, used) or _pick_inv(pools, other, 2, used)
